const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem(STORAGE_KEY) || 'it' } catch { return 'it' }
  })

  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, lang) } catch { /* ignore */ }
  }, [lang])

  function setLang(l) { setLangState(l) }
  function toggleLang() { setLangState(l => (l === 'it' ? 'en' : 'it')) }

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggleLang, t: dict[lang] }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLang() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLang must be used within LanguageProvider')
  return ctx
}
